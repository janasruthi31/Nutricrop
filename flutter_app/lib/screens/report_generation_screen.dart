import 'package:flutter/material.dart';
import '../services/api_client.dart';
import '../theme/app_theme.dart';
import '../widgets/common_widgets.dart';

class ReportGenerationScreen extends StatefulWidget {
  final Map<String, dynamic> recommendationData;
  final String? savedId;

  const ReportGenerationScreen({
    super.key,
    required this.recommendationData,
    this.savedId,
  });

  @override
  State<ReportGenerationScreen> createState() => _ReportGenerationScreenState();
}

class _ReportGenerationScreenState extends State<ReportGenerationScreen> {
  bool _isGenerating = false;
  bool _downloadSuccess = false;
  int? _pdfSizeBytes;
  String? _error;

  Future<void> _generateAndDownload() async {
    setState(() {
      _isGenerating = true;
      _error = null;
      _downloadSuccess = false;
    });

    try {
      String id = widget.savedId ?? '';
      if (id.isEmpty) {
        // Save first to get a permanent recommendation ID
        final saveRes = await ApiClient.instance.saveRecommendation(widget.recommendationData);
        id = saveRes['recommendation_id'];
      }

      // Download real PDF bytes generated by backend ReportLab
      final bytes = await ApiClient.instance.downloadRecommendationPdf(id);
      setState(() {
        _pdfSizeBytes = bytes.length;
        _downloadSuccess = true;
      });

      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Report generated successfully (${(bytes.length / 1024).toStringAsFixed(1)} KB)'),
          backgroundColor: AppTheme.primaryGreen,
        ),
      );
    } catch (e) {
      setState(() => _error = 'Failed to generate report: $e');
    } finally {
      if (mounted) setState(() => _isGenerating = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final crop = widget.recommendationData['crop'] ?? 'Crop';
    final district = widget.recommendationData['district'] ?? 'District';

    return Scaffold(
      appBar: AppBar(title: const Text('Download Recommendation Report')),
      body: SafeArea(
        child: Padding(
          padding: const EdgeInsets.all(24.0),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              Card(
                elevation: 2,
                child: Padding(
                  padding: const EdgeInsets.all(22.0),
                  child: Column(
                    children: [
                      Container(
                        padding: const EdgeInsets.all(16),
                        decoration: BoxDecoration(
                          color: const Color(0xFFFFEBEE),
                          shape: BoxShape.circle,
                        ),
                        child: const Icon(Icons.picture_as_pdf_rounded, color: Color(0xFFD32F2F), size: 48),
                      ),
                      const SizedBox(height: 16),
                      Text(
                        'Official Fertilizer Recommendation Report',
                        textAlign: TextAlign.center,
                        style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 17, color: AppTheme.textDark),
                      ),
                      const SizedBox(height: 6),
                      Text(
                        '$crop • $district District',
                        style: const TextStyle(fontSize: 14, color: AppTheme.textMuted),
                      ),
                      const SizedBox(height: 14),
                      const Divider(),
                      const SizedBox(height: 8),
                      const Text(
                        'Report includes verified TNAU STCR equations, NPK nutrient balance, optimal commercial fertilizer bag counts (45kg/50kg), retail prices, growth-stage split schedules, and agro-weather advisories.',
                        textAlign: TextAlign.center,
                        style: TextStyle(fontSize: 12.5, color: AppTheme.textMuted, height: 1.4),
                      ),
                    ],
                  ),
                ),
              ),
              const SizedBox(height: 24),
              if (_isGenerating)
                const LoadingView(message: 'Generating high-resolution ReportLab PDF on server...')
              else if (_error != null)
                Card(
                  color: const Color(0xFFFFEBEE),
                  child: Padding(
                    padding: const EdgeInsets.all(14.0),
                    child: Text(_error!, style: const TextStyle(color: Colors.red)),
                  ),
                )
              else if (_downloadSuccess) ...[
                Card(
                  color: AppTheme.lightGreen,
                  child: Padding(
                    padding: const EdgeInsets.all(16.0),
                    child: Row(
                      children: [
                        const Icon(Icons.check_circle_rounded, color: AppTheme.primaryGreen, size: 28),
                        const SizedBox(width: 14),
                        Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              const Text('PDF Generated & Ready', style: TextStyle(fontWeight: FontWeight.bold, color: AppTheme.darkGreen)),
                              Text('File size: ${(_pdfSizeBytes! / 1024).toStringAsFixed(1)} KB (PDF format)', style: const TextStyle(fontSize: 12, color: AppTheme.textDark)),
                            ],
                          ),
                        ),
                      ],
                    ),
                  ),
                ),
                const SizedBox(height: 18),
              ],
              const Spacer(),
              FilledButton.icon(
                onPressed: _isGenerating ? null : _generateAndDownload,
                icon: const Icon(Icons.download_rounded),
                label: Text(_downloadSuccess ? 'Download Again' : 'Generate & Download PDF'),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
